# tests/glyphs.py — collect every non-ASCII character used in the VR UI strings into js/glyphs.js,
# so the web font can be preloaded for canvas text. Re-run after changing any Japanese text:
#   python3 tests/glyphs.py
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
chars = set()
for f in sorted((root / 'js').glob('*.js')):
    if f.name == 'glyphs.js':
        continue
    chars |= {c for c in f.read_text(encoding='utf-8') if ord(c) > 127}
chars |= set('0123456789,.:×%!?/ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz')
s = ''.join(sorted(chars)).replace('\\', '\\\\').replace("'", "\\'")
(root / 'js' / 'glyphs.js').write_text(
    "// glyphs.js — generated by tests/glyphs.py: every character the VR panels draw (for font preloading)\n"
    f"export const GLYPHS = '{s}';\n", encoding='utf-8')
print(len(chars), 'glyphs')

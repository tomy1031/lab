const CDN_HOSTS = /^(cdn\.jsdelivr\.net|fonts\.googleapis\.com|fonts\.gstatic\.com)$/;

const PREFIX = 'starlight-';
const CACHE = PREFIX + VERSION;          // this folder's files, one cache per version
const CDN_CACHE = PREFIX + 'cdn';        // versioned CDN files and fonts, kept across versions
const STALL_MS = { navigate: 4000, other: 8000 };

const abs = (u) => new URL(u, self.location).href;

self.addEventListener('install', (e) => {
  self.skipWaiting();
  e.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(LOCAL.map((u) => new Request(abs(u), { cache: 'reload' })));
    await cacheCdn([...CDN, ...FONT_CSS]);
  })());
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith(PREFIX) && k !== CACHE && k !== CDN_CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

/** Run fn over items, n at a time. */
async function pool(items, n, fn) {
  let i = 0;
  await Promise.all(Array.from({ length: n }, async () => { while (i < items.length) await fn(items[i++]); }));
}

/** Fetch and keep CDN files that are not cached yet; failures are left for status() to report. */
async function cacheCdn(urls) {
  const cdn = await caches.open(CDN_CACHE);
  await pool([...new Set(urls)], 6, async (u) => {
    if (await cdn.match(u, { ignoreVary: true })) return;
    try {
      const res = await fetch(u, { mode: 'cors', credentials: 'omit' });
      if (res.ok) await cdn.put(u, res);
    } catch { /* offline or blocked: reported as missing */ }
  });
}

/** Every font file listed by the cached font stylesheets (one run at a time). */
let fontsBusy = null;
function cacheFonts() {
  fontsBusy ??= (async () => {
    const cdn = await caches.open(CDN_CACHE);
    const urls = new Set();
    for (const req of await cdn.keys()) {
      if (new URL(req.url).hostname !== 'fonts.googleapis.com') continue;
      const res = await cdn.match(req);
      if (!res || res.type === 'opaque') continue;
      for (const m of (await res.text()).matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)'"]+)\)/g)) urls.add(m[1]);
    }
    await cacheCdn([...urls]);
  })().finally(() => { fontsBusy = null; });
  return fontsBusy;
}

async function status() {
  const [cache, cdn] = await Promise.all([caches.open(CACHE), caches.open(CDN_CACHE)]);
  let missing = 0;
  for (const u of LOCAL) if (!(await cache.match(abs(u), { ignoreVary: true }))) missing++;
  for (const u of CDN) if (!(await cdn.match(u, { ignoreVary: true }))) missing++;
  return { type: 'status', version: VERSION, ready: missing === 0, missing, total: LOCAL.length + CDN.length };
}

// The page reports what it loaded (fonts and anything else from the CDNs) and asks how ready we are.
self.addEventListener('message', (e) => {
  const port = e.ports[0];
  const msg = e.data || {};
  if (msg.type !== 'status' && msg.type !== 'keep') return;
  e.waitUntil((async () => {
    if (msg.type === 'keep' && Array.isArray(msg.urls)) {
      const extra = msg.urls.filter((u) => { try { return CDN_HOSTS.test(new URL(u).hostname); } catch { return false; } });
      await cacheCdn([...CDN, ...FONT_CSS, ...extra]);
    }
    const s = await status();
    if (port) port.postMessage(s); else if (e.source) e.source.postMessage(s);
    if (msg.type === 'keep' && s.ready) await cacheFonts();
  })());
});

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** The cached copy of a request to this folder; page URLs match without their query (?emulate=…). */
async function cached(req) {
  const cache = await caches.open(CACHE);
  if (req.mode !== 'navigate') return cache.match(req, { ignoreVary: true });
  const url = new URL(req.url); url.search = ''; url.hash = '';
  const base = url.href;
  return (await cache.match(base, { ignoreVary: true }))
    || (await cache.match(base.endsWith('/') ? base + 'index.html' : base + '/', { ignoreVary: true }));
}

async function networkFirst(req) {
  const cache = await caches.open(CACHE);
  const key = (() => { if (req.mode !== 'navigate') return req; const u = new URL(req.url); u.search = ''; u.hash = ''; return u.href; })();
  const net = fetch(req).then((res) => {
    if (res.ok && res.type === 'basic') cache.put(key, res.clone()).catch(() => {});
    return res;
  });
  const hit = await cached(req);
  if (!hit) return net;
  return Promise.race([
    net.then((res) => (res.ok || res.type === 'opaqueredirect' ? res : hit)).catch(() => hit),
    sleep(req.mode === 'navigate' ? STALL_MS.navigate : STALL_MS.other).then(() => hit),
  ]);
}

async function cacheFirst(req) {
  const cdn = await caches.open(CDN_CACHE);
  const hit = await cdn.match(req.url, { ignoreVary: true });
  if (hit) return hit;
  // always CORS (both CDNs allow it), so a stylesheet stays readable for cacheFonts()
  const res = await fetch(req.url, { mode: 'cors', credentials: 'omit' });
  if (res.ok) cdn.put(req.url, res.clone()).catch(() => {});
  return res;
}

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.href.startsWith(self.registration.scope)) e.respondWith(networkFirst(req));
  else if (CDN_HOSTS.test(url.hostname)) e.respondWith(cacheFirst(req));
});

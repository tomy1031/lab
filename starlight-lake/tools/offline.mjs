// Writes the offline file list into sw.js: every file the two apps serve (not READMEs, not tools/),
// each folder that has an index.html (so "arcade/" opens offline as well as "arcade/index.html"),
// and a VERSION hashed from their contents, so a changed file makes browsers refresh their copy.
//
//   node tools/offline.mjs           update sw.js
//   node tools/offline.mjs --check   exit 1 if sw.js is out of date
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SKIP_DIRS = new Set(['tools', 'node_modules']);
const skipFile = (rel) => rel === 'sw.js' || /(^|\/)README\.md$/.test(rel) || rel.split('/').some((p) => p.startsWith('.'));

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    const rel = relative(root, p).split(sep).join('/');
    if (statSync(p).isDirectory()) { if (!SKIP_DIRS.has(name) && !name.startsWith('.')) walk(p, out); }
    else if (!skipFile(rel)) out.push(rel);
  }
  return out;
}

const files = walk(root);
const hash = createHash('sha256');
for (const f of files) hash.update(f + '\0').update(readFileSync(join(root, f))).update('\0');
const version = hash.digest('hex').slice(0, 12);

const entries = [];
for (const f of files) {
  if (f === 'index.html') entries.push('./');
  else if (f.endsWith('/index.html')) entries.push(f.slice(0, -'index.html'.length));
  entries.push(f);
}

const block = `// <generated by tools/offline.mjs>
const VERSION = '${version}';
const LOCAL = [
${entries.map((e) => `  '${e}',`).join('\n')}
];
// </generated>`;

const swPath = join(root, 'sw.js');
const sw = readFileSync(swPath, 'utf8');
const next = sw.replace(/\/\/ <generated by tools\/offline\.mjs>[\s\S]*?\/\/ <\/generated>/, block);
if (next === sw) {
  console.log(`sw.js is up to date (${entries.length} files, version ${version})`);
} else if (process.argv.includes('--check')) {
  console.error('sw.js is out of date: run node tools/offline.mjs');
  process.exit(1);
} else {
  writeFileSync(swPath, next);
  console.log(`sw.js updated: ${entries.length} files, version ${version}`);
}
